require('reflect-metadata');
require('ts-node/register/transpile-only');
const assert=require('node:assert/strict');
const {randomUUID,randomBytes,createHash}=require('node:crypto');
const {Client}=require('pg');
const {DataSource}=require('typeorm');
const {JwtService}=require('@nestjs/jwt');
const {ConfigService}=require('@nestjs/config');
const {hash}=require('bcrypt');
const {User}=require('../../src/users/entities/user.entity');
const {UsersService}=require('../../src/users/users.service');
const {AuthService}=require('../../src/auth/auth.service');
const {JwtStrategy}=require('../../src/auth/strategies/jwt.strategy');
const url=process.env.AUTH_TEST_DATABASE_URL;
if(!url||!['127.0.0.1','localhost'].includes(new URL(url).hostname))throw Error('AUTH_TEST_DATABASE_URL must reference a disposable local PostgreSQL');
const database='auth_test_'+randomUUID().replaceAll('-','');
const admin=new Client({connectionString:url});let db;
(async()=>{
 await admin.connect();await admin.query(`CREATE DATABASE "${database}"`);
 const target=new URL(url);target.pathname='/'+database;
 db=new DataSource({type:'postgres',url:target.toString(),entities:[__dirname+'/../../src/**/*.entity.ts'],migrations:[__dirname+'/../../src/database/migrations/*.ts'],synchronize:false});
 await db.initialize();await db.runMigrations();
 const users=new UsersService(db.getRepository(User));
 const config=new ConfigService({JWT_ACCESS_SECRET:randomBytes(32).toString('hex'),JWT_REFRESH_SECRET:randomBytes(32).toString('hex'),JWT_ACCESS_EXPIRES_IN:'15m',JWT_REFRESH_EXPIRES_IN:'7d'});
 const jwt=new JwtService();const auth=new AuthService(users,jwt,config,{});
 const secret='Only-A-Synthetic-Test-Password';
 const user=await users.create('Session test','sessions@example.test',await hash(secret,4));
 await db.getRepository(User).update(user.id,{emailVerifiedAt:new Date()});
 const login=()=>auth.login({email:user.email,password:secret});
 const first=await login();const second=await login();
 assert.notEqual(first.refreshToken,second.refreshToken);
 assert.equal(first.refreshToken.slice(0,72),second.refreshToken.slice(0,72));
 await assert.rejects(()=>auth.refresh(first.refreshToken));
 console.log('PASS full-token digest and same-second unique JWTs; old login rejected');
 const concurrent=await Promise.allSettled([auth.refresh(second.refreshToken),auth.refresh(second.refreshToken)]);
 assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,1);
 const fresh=concurrent.find(r=>r.status==='fulfilled').value;
 await assert.rejects(()=>auth.refresh(second.refreshToken));
 console.log('PASS database compare-and-swap permits only one concurrent refresh');
 await auth.logout(second.refreshToken);
 const afterStaleLogout=await auth.refresh(fresh.refreshToken);
 await auth.logout(afterStaleLogout.refreshToken);
 await assert.rejects(()=>auth.refresh(afterStaleLogout.refreshToken));
 console.log('PASS stale logout cannot revoke new session; current logout revokes');
 const beforePassword=await login();
 const strategy=new JwtStrategy(config,users);const accessPayload=jwt.verify(beforePassword.accessToken,{secret:config.get('JWT_ACCESS_SECRET')});
 await strategy.validate(accessPayload);
 await users.changePassword(user.id,await hash(secret,4));
 await assert.rejects(()=>strategy.validate(accessPayload));
 await assert.rejects(()=>auth.refresh(beforePassword.refreshToken));
 console.log('PASS password version revokes access and refresh, including same-second updates');
 const legacy=await login();await users.setRefreshTokenHash(user.id,await hash(legacy.refreshToken,4));
 await assert.rejects(()=>auth.refresh(legacy.refreshToken));
 console.log('PASS bcrypt legacy sessions fail closed');
 const verifyToken=randomBytes(32).toString('hex');const digest=s=>createHash('sha256').update(s).digest('hex');
 await users.saveVerificationToken(user.id,digest(verifyToken),new Date(Date.now()+60000),new Date());
 const verifies=await Promise.allSettled([auth.verifyEmail(verifyToken),auth.verifyEmail(verifyToken)]);
 assert.equal(verifies.filter(r=>r.status==='fulfilled').length,1);
 const resetToken=randomBytes(32).toString('hex');
 await users.savePasswordReset(user.id,digest(resetToken),new Date(Date.now()+60000));
 const resets=await Promise.allSettled([auth.resetPassword(resetToken,secret),auth.resetPassword(resetToken,secret)]);
 assert.equal(resets.filter(r=>r.status==='fulfilled').length,1);
 console.log('PASS reset and verification tokens consumed once under concurrency');
 console.log('ALL SESSION INTEGRATION CHECKS PASSED');
})().catch(e=>{console.error(e.name,e.message);process.exitCode=1}).finally(async()=>{if(db?.isInitialized)await db.destroy();await admin.query(`DROP DATABASE IF EXISTS "${database}" WITH (FORCE)`);await admin.end()});
